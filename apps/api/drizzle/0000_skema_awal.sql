-- View rekap. Ditulis manual karena Prisma tidak membuat view dari schema.prisma.
-- Setiap unit dipetakan ke unit induk tertingginya lewat penelusuran pohon unit_kerja.
CREATE VIEW "v_unit_induk" AS
WITH RECURSIVE pohon (unit_kerja_id, induk_id) AS (
  SELECT id, id FROM unit_kerja WHERE parent_id IS NULL
  UNION ALL
  SELECT u.id, p.induk_id FROM unit_kerja u INNER JOIN pohon p ON u.parent_id = p.unit_kerja_id
)
SELECT unit_kerja_id, induk_id FROM pohon;

-- Jumlah kegiatan aktif (belum dihapus) per unit induk, bulan kalender WIB, dan jenis.
-- Waktu disimpan sebagai timestamptz sehingga dikonversi ke Asia/Jakarta sebelum diambil bulannya (NFR-06).
CREATE VIEW "v_rekap_bulanan" AS
SELECT
  ui.induk_id AS unit_induk_id,
  to_char(k.tgl_mulai AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM') AS bulan,
  k.jenis_id AS jenis_id,
  COUNT(*)::integer AS jumlah
FROM kegiatan k
INNER JOIN v_unit_induk ui ON ui.unit_kerja_id = k.unit_kerja_id
WHERE k.deleted_at IS NULL
GROUP BY ui.induk_id, to_char(k.tgl_mulai AT TIME ZONE 'Asia/Jakarta', 'YYYY-MM'), k.jenis_id;
